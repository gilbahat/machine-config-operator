// copyPreservingAttrs copies src to dst preserving mode, ownership, times and xattrs.
func copyPreservingAttrs(src, dst string) error {
	if out, err := exec.Command("cp", "-a", "--reflink=auto", src, dst).CombinedOutput(); err != nil {
		return fmt.Errorf("%s: %w", string(out), err)
	}
	return nil
}

// writeSystemLog sends message to the journal via logger(1).
func writeSystemLog(message string) error {
	logger := exec.Command("logger")
	var log bytes.Buffer
	log.WriteString(message)
	logger.Stdin = &log
	return logger.Run()
}

// logHostServiceState logs boot history and failed systemd units at startup.
func logHostServiceState(cmdRunner CommandRunner) {
	boots, err := cmdRunner.RunGetOut("journalctl", "--list-boots")
	if err != nil {
		klog.Errorf("Listing boots: %v", err)
	}
	klog.Info("journalctl --list-boots:" + string(boots))

	// Since nothing in the cluster today watches systemd units, let's
	// at least capture them in our logs to start.  See also
	// https://github.com/openshift/machine-config-operator/issues/1365
	// This only captures units that started *before* the MCD, we need
	// to also watch dynamically of course.
	//
	// also xref https://github.com/coreos/console-login-helper-messages/blob/e8a849f4c23910e7c556c10719911cc59873fc23/usr/share/console-login-helper-messages/profile.sh
	failedServices, err := cmdRunner.RunGetOut("systemctl", "list-units", "--state=failed", "--no-legend")
	switch {
	case err != nil:
		klog.Errorf("Listing failed systemd services: %v", err)
	case len(failedServices) > 0:
		klog.Info("systemctl --failed:" + string(failedServices))
	default:
		klog.Info("systemd service state: OK")
	}
}

