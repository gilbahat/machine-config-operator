// mkdirAsCoreUser creates dir (and parents) as the core user with mode 0700.
func mkdirAsCoreUser(dir string) error {
	return exec.Command("runuser", "-u", constants.CoreUserName, "--", "mkdir", "-m", "0700", "-p", dir).Run()
}

func getUserPasswordHash(user string) (string, error) {
	shadowOut, err := exec.Command("getent", "shadow", user).CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("failed to check password hash for %s: %w", user, err)
	}
	shadowSlice := strings.SplitN(strings.TrimSpace(string(shadowOut)), ":", 3)
	if len(shadowSlice) >= 2 {
		return shadowSlice[1], nil
	}
	return "", nil
}

// setUserPasswordHash stores an already-encrypted password hash for user.
func setUserPasswordHash(user, hash string) error {
	if out, err := exec.Command("usermod", "-p", hash, user).CombinedOutput(); err != nil {
		return fmt.Errorf("%s:%w", out, err)
	}
	return nil
}

// runUpdateCATrust regenerates the system trust store, returning stderr on failure.
func runUpdateCATrust() (string, error) {
	cmd := exec.Command(constants.UpdateCATrustCommand)
	var stderr bytes.Buffer
	cmd.Stdout = os.Stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	return stderr.String(), err
}

